// ════════════════════════════════════════════════════════════════════════════
// gen-tools-list-snapshot.mjs - the `tools/list` snapshot (Story 39.6, DW-573; AD-15, AD-2).
//
// WHAT THE SNAPSHOT IS
//   packages/iris-mcp-all/src/__tests__/fixtures/tools-list-snapshot.json pins the real
//   `tools/list` entry (title, description, inputSchema, annotations, and outputSchema
//   when present) of every tool of the five built servers under preset `full`. It is
//   GENERATED and never edited by hand. The capture and the comparison live in
//   scripts/lib/tools-list-snapshot-core.mjs, which the default-suite test
//   packages/iris-mcp-all/src/__tests__/tools-list-snapshot.test.ts also imports, so the
//   CLI and the test cannot disagree.
//
// THE CHECK IS ONE-DIRECTIONAL
//   Every snapshot entry must still be listed, and each pinned field must deep-equal the
//   live one after a sorted-key canonicalization. Any difference, an additive one
//   included, fails. A live tool the snapshot does not list is reported and allowed.
//
// USAGE (a generator of a pinned artifact has a no-write mode and refuses to overwrite
// without --force, as scripts/gen-governance-baseline.mjs does)
//
//   node scripts/gen-tools-list-snapshot.mjs --check
//       SAFE. Captures the live tools/list from the built dists and compares it with the
//       committed snapshot. Writes NOTHING. Exit 0 when nothing differs (new tools are
//       listed, never a failure); exit 1 when an entry vanished or a pinned field differs,
//       naming `<package> <tool>.<field>` and the first differing JSON path.
//       (npm: `pnpm gen:tools-list-snapshot:check`)
//
//   node scripts/gen-tools-list-snapshot.mjs            (no flag)
//       REFUSES. Prints the refusal and exits 2 WITHOUT writing.
//       (npm: `pnpm gen:tools-list-snapshot` - also refuses without --force)
//
//   node scripts/gen-tools-list-snapshot.mjs --force
//       WRITES the snapshot from the live capture. Legitimate only in the story that
//       deliberately changes a listed tools/list entry (its title, description, schema or
//       annotations) or upgrades the SDK or zod, which moves every entry; and only after
//       rebuilding every package, so the capture reads the code that ships. The regenerate
//       diff is the reviewable record of the change, and the story adds a CHANGELOG line.
//       Never use it to turn a failing --check green without understanding the drift.
//
//   Exit codes: 0 success; 1 drift, or an unexpected error; 2 refusal (no flag, an unknown
//   flag, or both flags) or a stale or missing dist (rebuild the named package first).
//   Nothing contacts IRIS.
// ════════════════════════════════════════════════════════════════════════════

import { existsSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import {
  SNAPSHOT_RELATIVE_PATH,
  assertSnapshotShape,
  canonicalize,
  captureToolsList,
  compareSnapshot,
  readSnapshot,
  serializeSnapshot,
  staleDistMessage,
  staleDists,
} from './lib/tools-list-snapshot-core.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const snapshotPath = resolve(root, SNAPSHOT_RELATIVE_PATH);

const SNAPSHOT_COMMENT =
  'GENERATED by scripts/gen-tools-list-snapshot.mjs - never edit by hand. Pins the tools/list entry ' +
  '(title, description, inputSchema, annotations, and outputSchema when present) of every tool of the ' +
  'five built servers under preset full. The check is one-directional: every entry here must still be ' +
  'listed and unchanged; a tool absent from this file is reported and allowed. A deliberate change to a ' +
  'listed entry regenerates this file with `pnpm gen:tools-list-snapshot --force` after rebuilding every package.';

const KNOWN_FLAGS = ['--check', '--force'];

function out(text) {
  process.stdout.write(`${text}\n`);
}

function err(text) {
  process.stderr.write(`${text}\n`);
}

/** The refusal text for an argument list that is not exactly one of `--check` / `--force`, or undefined when it is. */
function refusalReason(argv) {
  const unknown = argv.filter((arg) => !KNOWN_FLAGS.includes(arg));
  if (unknown.length > 0) return `unknown argument(s): ${unknown.join(' ')}`;
  const check = argv.includes('--check');
  const force = argv.includes('--force');
  if (check && force) return '--check and --force are mutually exclusive';
  if (!check && !force) return 'no flag given';
  return undefined;
}

/** `--check`: compare the committed snapshot with the live capture; write nothing. */
function runCheck(live) {
  let committed;
  try {
    committed = readSnapshot(root);
  } catch (error) {
    err(
      `gen-tools-list-snapshot --check: could not read the committed snapshot at\n${snapshotPath}.\n` +
        `Underlying error: ${error?.message ?? error}`,
    );
    return 1;
  }
  const { problems, added } = compareSnapshot(committed, live);

  out('gen-tools-list-snapshot --check (no-write)');
  out(`  committed entries:        ${committed.entryCount}`);
  out(`  live entries:             ${live.entryCount}`);
  out(`  new tools (allowed):      ${added.length}`);
  for (const line of added) out(`    + ${line}`);

  if (problems.length > 0) {
    err('');
    err(`The tools/list snapshot DIFFERS from the live tools/list - ${problems.length} problem(s):`);
    for (const line of problems) err(`  - ${line}`);
    err('');
    err(
      'A pinned entry changed or vanished. If the change is intended, rebuild every package, run\n' +
        '`pnpm gen:tools-list-snapshot --force` once, review the diff, and add a CHANGELOG line.\n' +
        'If it is not, restore the entry.',
    );
    return 1;
  }
  out('');
  out(`OK - every one of the ${committed.entryCount} snapshot entries is still listed, unchanged.`);
  return 0;
}

/** `--force`: write the snapshot from the live capture. A capture that fails the shape check is never written. */
function runForce(live) {
  assertSnapshotShape(live);

  if (existsSync(snapshotPath)) {
    try {
      const { problems, added } = compareSnapshot(readSnapshot(root), live);
      if (problems.length > 0) {
        out(`Re-pinning ${problems.length} changed or vanished entr${problems.length === 1 ? 'y' : 'ies'}:`);
        for (const line of problems) out(`  - ${line}`);
      }
      if (added.length > 0) {
        out(`Pinning ${added.length} new tool${added.length === 1 ? '' : 's'}:`);
        for (const line of added) out(`  + ${line}`);
      }
    } catch {
      out('No readable previous snapshot to compare with.');
    }
  }

  const document = {
    comment: SNAPSHOT_COMMENT,
    capturedAt: new Date().toISOString(),
    sdkVersion: live.sdkVersion,
    zodVersion: live.zodVersion,
    entryCount: live.entryCount,
    servers: canonicalize(live.servers),
  };
  writeFileSync(snapshotPath, serializeSnapshot(document), 'utf-8');

  out(`Generated ${snapshotPath}`);
  out(`entryCount: ${document.entryCount}`);
  out(`sdkVersion: ${document.sdkVersion}`);
  out(`zodVersion: ${document.zodVersion}`);
  for (const [pkg, entries] of Object.entries(document.servers)) {
    out(`  ${pkg}: ${Object.keys(entries).length} entries`);
  }
  return 0;
}

async function main(argv) {
  // Refusals come first and touch neither the dists nor the snapshot.
  const refusal = refusalReason(argv);
  if (refusal !== undefined) {
    err(
      `gen-tools-list-snapshot: REFUSING (${refusal}); nothing was written.\n` +
        `\n` +
        `The tools/list snapshot at ${snapshotPath} is a pinned artifact: it is regenerated only\n` +
        `by the story that deliberately changes a listed tools/list entry, never to make a check pass.\n` +
        `\n` +
        `  - To VERIFY the snapshot against the live tools/list (no write):\n` +
        `        node scripts/gen-tools-list-snapshot.mjs --check\n` +
        `        (or: pnpm gen:tools-list-snapshot:check)\n` +
        `  - To regenerate it (after rebuilding every package):\n` +
        `        node scripts/gen-tools-list-snapshot.mjs --force\n`,
    );
    return 2;
  }

  const mode = argv.includes('--check') ? '--check' : '--force';
  const stale = staleDists(root);
  if (stale.length > 0) {
    err(`gen-tools-list-snapshot ${mode}: ${staleDistMessage(stale)}`);
    return 2;
  }

  const live = await captureToolsList(root);
  return mode === '--check' ? runCheck(live) : runForce(live);
}

process.exitCode = await main(process.argv.slice(2));
